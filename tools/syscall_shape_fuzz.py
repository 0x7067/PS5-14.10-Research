#!/usr/bin/env python3
"""Fuzz the size and pointer fields of the syscalls that actually reach their body.

Every handler measured on 14.10 either returns -1 (gated), dies (nosys trampoline under
the default SIGSYS disposition), or accepts the call and returns a status. The third group
is the population this tool fuzzes: for each entry it takes the argument template that was
measured to reach the body, moves the user pointer between a mapped page, the last bytes of
that page, NULL and an unmapped address, and drives the length/count field through boundary
values. A handler that validates its copy against the mapping survives all of them; one
that trusts the field faults, and the fault is the finding.

One connection per case: a fault leaves the loader's signal handler looping, so a shared
connection would lose every case after the first crash. The runner stops at the first
CONNECT_FAILED so the report names the exact case that took the process down.

    python tools/syscall_shape_fuzz.py --save results/fuzz/shape_run1.json
    python tools/syscall_shape_fuzz.py --limit 50 --dry-run
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SEND = os.path.join(HERE, "send_probe.py")

# Argument templates. P is the user pointer, S the length/count field, K a second pointer.
# Each template is the shape that was measured to reach the handler body, not a guess:
# the probe that established it is named in the comment.
SPECS = [
    # sys, name, template, pointer slots, size slots, note
    (532, "gpu_dispatch 0x18", [0x18, 0, "P", 0, "S", 0], [2], [4], "307a/428a: 0x800D0202"),
    (532, "gpu_dispatch 0x2F", [0x2F, 0, "P", 0, "S", 0], [2], [4], "428a: returns 0"),
    (601, "mdbg 0x00", [0x00, "P", "S", 0, 0, 0], [1], [2], "322a: ret 0, writes 0x100"),
    (601, "mdbg 0x10", [0x10, "P", "S", 0, 0, 0], [1], [2], "dossier: 0x1000 alloc then copyout"),
    (602, "sys602", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (606, "sys606", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (617, "set_gpo", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (620, "free_stack", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (624, "vm_map_timestamp", ["P", "S", 0, 0, 0, 0], [0], [1], "52b: counter"),
    (638, "utc", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (639, "localtime", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (640, "set_uevt", ["P", "S", 0, 0, 0, 0], [0], [1], "sweep: returns 0"),
    (657, "blockpool_batch", ["P", "S", "K", 0, 0, 0], [0, 2], [1], "350a: count 0 ok"),
    (669, "aio_submit", [1, "P", "S", 1, "K", 0], [1, 4], [2], "352a: works"),
    (674, "vm_map", ["P", "S", 0, 0, 0, 0], [0], [1], "55e: 317 regions"),
    (547, "region_query", ["P", "K", "S", 0, 0, 0], [0, 1], [2], "247a: region record"),
    (549, "osem_create", ["P", 0, 0, "S", 0, 0], [0], [3], "349b: (name, attrs, init, max)"),
    (551, "osem_open", ["P", 0, 0, 0, 0, 0], [0], [], "349c: name lookup"),
    (557, "namedobj_create", ["P", 0, 0, 0, 0, 0], [0], [], "334a: handle"),
    (538, "evf_create", ["P", 0, 0, 0, 0, 0], [0], [], "336a: handle"),
    (540, "evf_lookup", ["P", 0, 0, 0, 0, 0], [0], [], "336a: registry"),
    (189, "fstat", ["P", "K", 0, 0, 0, 0], [0, 1], [], "353c: works"),
]

SIZES = [0, 1, 8, 0x10, 0x3F, 0x40, 0x100, 0x800, 0x1000, 0x2000,
         0x7FFFFFFF, 0xFFFFFFFF, 0xFFFFFFFFFFFFFFFF]
# Only pointers that stay inside the mapping. A failed user copy makes the kernel deliver
# SIGSEGV to the process (measured: 532 cmd 0x18 with a hole pointer produced a 286 KB dump
# loop), and the loader's handler does not advance past the faulting instruction, so a bad
# pointer tests the signal path, not the handler. Boundary *sizes* on a valid pointer are
# the shape that can expose a kernel-side overrun.
POINTERS = [
    ("page", 0),
    ("page_end", -8),
]

CASE_TEMPLATE = """-- generated by tools/syscall_shape_fuzz.py: {name}
print("=== FUZZ {index} {name} ===")
local function to_num(v)
    if type(v) == "table" and v.tonumber then return v:tonumber() end
    return tonumber(v) or 0
end
local function make_syscall(num)
    local t = {{}}
    for k, v in pairs(syscall.pipe) do t[k] = v end
    t.syscall_no = num
    setmetatable(t, getmetatable(syscall.pipe))
    return t
end
local function sgn(v)
    local h, l = 0, to_num(v)
    if type(v) == "table" then h = v.h or 0; l = v.l and to_num(v.l) or 0 end
    local x = h * 4294967296 + l
    if x >= 9223372036854775808 then x = x - 18446744073709551616 end
    return x
end
-- The buffer is an isolated mmap with a hole on each side, not memory.alloc: the shape
-- fuzzer's first run died on a pointer "before the buffer" that was still inside the
-- loader's heap, and the handler wrote its status dword there (430a shows it writes exactly
-- four bytes). That was self-corruption, not the kernel. With the neighbours unmapped, the
-- same pointer is a real hole.
local trio = 0
local function sgn2(v) return sgn(v) end
trio = (function()
    local a = 0
    local sc = make_syscall(477)
    local ok, rv = pcall(function() return sc(uint64(0), uint64(0x3000), uint64(7), uint64(0x1002), uint64(0xFFFFFFFF), uint64(0)) end)
    if ok then a = sgn(rv) end
    return a
end)()
local page = 0
if trio > 0 then
    page = trio + 0x1000
    local sc73 = make_syscall(73)
    pcall(function() sc73(uint64(trio), uint64(0x1000), uint64(0), uint64(0), uint64(0), uint64(0)) end)
    pcall(function() sc73(uint64(trio + 0x2000), uint64(0x1000), uint64(0), uint64(0), uint64(0), uint64(0)) end)
else
    page = sgn(memory.alloc(0x1000))
end
local k = 0
while k < 0x1000 do memory.write_dword(page + k, 0); k = k + 4 end
local p = page + ({ptr_offset})
local a = {{{args}}}
local sc = make_syscall({num})
local ok, rv = pcall(function()
    return sc(uint64(a[1] or 0), uint64(a[2] or 0), uint64(a[3] or 0), uint64(a[4] or 0), uint64(a[5] or 0), uint64(a[6] or 0))
end)
if not ok then print("[R] EXC " .. tostring(rv)) else print("[R] rv=" .. tostring(sgn(rv))) end
print("=== FUZZ DONE {index} ===")
"""


def build_case(index, num, name, template, ptr_slot, ptr_offset, size_slot, size):
    args = []
    for i, token in enumerate(template):
        if token == "P" and i == ptr_slot:
            args.append("p")
        elif token == "K" and i == ptr_slot:
            args.append("p")
        elif token == "P" or token == "K":
            args.append("sgn(page)")
        elif token == "S":
            args.append(str(size) if i == size_slot else "0x40")
        else:
            args.append(str(token))
    body = ", ".join(args)
    return CASE_TEMPLATE.format(index=index, name=name, num=num,
                                ptr_offset=ptr_offset if ptr_offset is not None else 0,
                                args=body)


def run_case(case_path, ip, timeout):
    cmd = [sys.executable, SEND, case_path, "--ip", ip,
           "--timeout", str(timeout), "--total-timeout", str(timeout + 8)]
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    try:
        done = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout + 20, env=env)
    except subprocess.TimeoutExpired:
        return {"status": "HARNESS_TIMEOUT", "output": ""}
    out = (done.stdout or "") + (done.stderr or "")
    status = "UNKNOWN"
    m = re.search(r"Status:\s*(\w+)", out)
    if m:
        status = m.group(1)
    return {"status": status, "output": out}


def cases(limit=None):
    out = []
    for (num, name, template, ptr_slots, size_slots, note) in SPECS:
        if not ptr_slots or not size_slots:
            continue
        for ptr_slot in ptr_slots:
            for (plabel, poff) in POINTERS:
                for size_slot in size_slots:
                    for size in SIZES:
                        out.append((num, name, template, ptr_slot, plabel, poff, size_slot, size, note))
                        if limit and len(out) >= limit:
                            return out
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ip", default="192.168.1.121")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--timeout", type=float, default=8.0)
    ap.add_argument("--delay", type=float, default=0.05)
    ap.add_argument("--save", default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--jsonl", default=None, help="append every case result here as it runs")
    args = ap.parse_args()

    todo = cases(args.limit)
    print("cases: %d" % len(todo))
    if args.dry_run:
        for i, c in enumerate(todo[:20]):
            print("  %d %s ptr=%s size_slot=%d size=0x%X" % (i, c[1], c[4], c[6], c[7]))
        return 0

    if args.jsonl and os.path.exists(args.jsonl):
        os.remove(args.jsonl)
    results = []
    killer = None
    tmpdir = tempfile.mkdtemp(prefix="shapefuzz_")
    for i, (num, name, template, ptr_slot, plabel, poff, size_slot, size, note) in enumerate(todo):
        path = os.path.join(tmpdir, "case_%04d.lua" % i)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(build_case(i, num, name, template, ptr_slot, poff, size_slot, size))
        got = run_case(path, args.ip, args.timeout)
        row = {"index": i, "sys": num, "name": name, "ptr": plabel,
               "size": size, "status": got["status"], "note": note}
        rv = re.search(r"\[R\] rv=(-?\d+)", got["output"])
        if rv:
            row["rv"] = int(rv.group(1))
        results.append(row)
        if args.jsonl:
            with open(args.jsonl, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(row) + "\n")
        if got["status"] not in ("COMPLETE",):
            print("  case %d %s ptr=%s size=0x%X -> %s" % (i, name, plabel, size, got["status"]))
        if got["status"] in ("CONNECT_FAILED", "CONNECTION_REFUSED", "HARNESS_TIMEOUT", "NO_OUTPUT"):
            killer = row
            print("loader is down; the case that took it down is case %d" % i)
            break
        if (i + 1) % 50 == 0:
            print("  %d/%d done" % (i + 1, len(todo)))
        if args.delay:
            time.sleep(args.delay)

    print("ran %d cases" % len(results))
    kinds = {}
    for row in results:
        kinds[row["status"]] = kinds.get(row["status"], 0) + 1
    print("statuses:", kinds)
    interesting = [r for r in results if r.get("status") not in ("COMPLETE",) or r.get("rv") not in (None, -1)]
    print("non-(-1) or non-complete: %d" % len(interesting))
    for row in interesting[:40]:
        print("  %s" % json.dumps(row))

    if args.save:
        os.makedirs(os.path.dirname(os.path.abspath(args.save)), exist_ok=True)
        with open(args.save, "w", encoding="utf-8") as fh:
            json.dump({"cases": results, "killer": killer}, fh, indent=1)
        print("saved", args.save)
    return 0


if __name__ == "__main__":
    sys.exit(main())
