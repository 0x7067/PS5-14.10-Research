#!/usr/bin/env python3
"""Build an argument-contract table from the 13.60 handler analyses.

The 145 files under results/kernel_handlers/analysis/ describe each Sony
syscall handler recovered from the 13.60 kernel capture. Their prose contains
the only argument-level information the project has: how many slots a handler
takes, which slot offsets are dereferenced, and how many bytes are copied back
to the caller.

Probes that pass six zero arguments cannot reach such a handler, and the
resulting -1 is indistinguishable from "no handler". This table exists so a
probe can be written against a contract instead of a guess.

Usage:
    python tools/syscall_contracts.py            # print the table
    python tools/syscall_contracts.py --write    # rewrite docs/SYSCALL_CONTRACTS_13_60.md
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANALYSIS = ROOT / "results" / "kernel_handlers" / "analysis"
DECOMPILED = ROOT / "results" / "kernel_handlers" / "decompiled"
OUT = ROOT / "docs" / "SYSCALL_CONTRACTS_13_60.md"

NUMBER = re.compile(r"sys_(\d+)(?:_deep)?\.md$")
TITLES = [
    re.compile(r"^#\s+Handler\s+\d+:\s*(.+)$"),
    re.compile(r"^#\s+Deep Analysis:\s*sys\s*\d+\s*\((.*?)\)$"),
    re.compile(r"^#\s+Deep RE:\s*sys\s*\d+\s*[—-]\s*(.*?)\s*\(.*$"),
    re.compile(r"^#\s+Handler\s+\d+\s+Analysis$"),
]
NARG_SLOTS = re.compile(r"\*\*(\d+)\s+argument slots\*\*")
NARG_EQ = re.compile(r"narg\s*=\s*(\d+)")
ARG_OFFSET = re.compile(r"argument\s*\+\s*(0x[0-9a-fA-F]+|\d+)")
COPYOUT_BYTES = re.compile(r"copy\w*\s+(?:of\s+)?(?:the\s+)?(0x[0-9a-fA-F]+|\d+)[- ]byte")
USER_POINTER = re.compile(r"(?:the\s+)?user(?:\s+pointer|\s+array|\s+buffer)", re.IGNORECASE)
ARGS_STRUCT = re.compile(r"struct (?:sys_|h)(\d+)_args\s*\{([^}]*)\}", re.S)


def recovered_args(number):
    """Return the recovered argument field names from the decompiled handler."""
    path = DECOMPILED / ("sys_%d.c" % number)
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8", errors="replace")
    match = ARGS_STRUCT.search(text)
    if not match:
        return []
    names = []
    body = re.sub(r"/\*.*?\*/", " ", match.group(2), flags=re.S)
    for raw in body.split(";"):
        raw = re.sub(r"\[[^\]]*\]", "", raw).strip()
        if not raw:
            continue
        identifiers = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", raw)
        if not identifiers:
            continue
        name = identifiers[-1]
        if name.startswith("pad") or name.startswith("unknown"):
            continue
        names.append(name)
    return names


def describe(path):
    """Return one contract row for an analysis file, or None when it is empty."""
    text = path.read_text(encoding="utf-8", errors="replace")
    number = int(NUMBER.search(path.name).group(1))

    title = ""
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("#"):
            continue
        for pattern in TITLES:
            match = pattern.match(stripped)
            if match:
                title = match.group(1).strip() if match.groups() else "(static REA review)"
                break
        if title:
            break
    if not title:
        title = "(no description recovered)"

    slots = NARG_SLOTS.search(text)
    nargs = int(slots.group(1)) if slots else None
    if nargs is None:
        nargs_eq = NARG_EQ.search(text)
        nargs = int(nargs_eq.group(1)) if nargs_eq else None

    offsets = sorted({int(value, 0) for value in ARG_OFFSET.findall(text)})
    copies = COPYOUT_BYTES.findall(text)
    copyout = max((int(value, 0) for value in copies), default=None)
    touches_user_pointer = bool(USER_POINTER.search(text))

    return {
        "syscall": number,
        "title": title,
        "nargs": nargs,
        "offsets": offsets,
        "copyout": copyout,
        "user_pointer": touches_user_pointer,
        "args": recovered_args(number),
    }


def rows():
    contracts = []
    for path in sorted(ANALYSIS.glob("sys_*.md"), key=lambda p: int(NUMBER.search(p.name).group(1))):
        contract = describe(path)
        if contract:
            contracts.append(contract)
    return contracts


def render(contracts):
    lines = [
        "# Sony syscall argument contracts (13.60 capture)",
        "",
        "Generated by `tools/syscall_contracts.py` from `results/kernel_handlers/analysis/`.",
        "Every row is a 13.60 observation; 14.10 behaviour still has to be measured.",
        "",
        "`slots` is the syscall's argument count, `arg+` lists the argument offsets the",
        "handler dereferences, `copyout` is the largest byte count copied back to the",
        "caller, and `user ptr` marks a handler whose prose names a user pointer or",
        "buffer. A probe that passes six zeroes reaches none of these contracts.",
        "",
        "`args` shows the recovered argument field names when the decompiled handler",
        "carries an analyst struct for this syscall; those names are the contract a",
        "probe should be built from.",
        "",
        "| syscall | slots | args | arg+ | copyout | user ptr | description |",
        "|---:|---:|---|---:|---|---|---|",
    ]
    for contract in contracts:
        offsets = ", ".join("0x%02x" % value for value in contract["offsets"]) or "-"
        copyout = "0x%x" % contract["copyout"] if contract["copyout"] else "-"
        slots = str(contract["nargs"]) if contract["nargs"] is not None else "-"
        lines.append(
            "| %d | %s | %s | %s | %s | %s | %s |"
            % (
                contract["syscall"],
                slots,
                ", ".join(contract["args"]) or "-",
                offsets,
                copyout,
                "yes" if contract["user_pointer"] else "-",
                contract["title"].replace("|", "/"),
            )
        )
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the table to %s" % OUT)
    args = parser.parse_args()

    contracts = rows()
    table = render(contracts)
    if args.write:
        OUT.write_text(table, encoding="utf-8")
        print("wrote %s (%d handlers)" % (OUT, len(contracts)))
    else:
        print(table)


if __name__ == "__main__":
    main()
